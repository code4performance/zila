//! Settings, test hooks, per-thread state and the source map of generated text.

use std::cell::{Cell, RefCell};
use std::sync::Mutex;

/// How comptime runs behave. Set by the command line (`--comptime-timeout`,
/// `--no-comptime-cache`, `--comptime-dump`) and by tests.
#[derive(Clone, Debug)]
pub struct Settings {
    /// Wall-clock limit of one run of generators, in seconds.
    pub timeout_secs: u64,
    /// Read and write the on-disk cache.
    pub cache: bool,
    /// Print each generated text to standard error.
    pub dump: bool,
    /// Where the cache lives; the system temporary directory when unset.
    pub cache_dir: Option<std::path::PathBuf>,
    /// Added to the compiler version in the cache key.
    pub version_tag: String,
}

static SETTINGS: Mutex<Settings> =
    Mutex::new(Settings { timeout_secs: 5, cache: true, dump: false, cache_dir: None, version_tag: String::new() });

static LAUNCHES: Mutex<Vec<String>> = Mutex::new(Vec::new());

pub fn settings() -> Settings {
    SETTINGS.lock().unwrap().clone()
}

pub fn set_timeout_secs(secs: u64) {
    SETTINGS.lock().unwrap().timeout_secs = secs;
}

pub fn set_cache_enabled(on: bool) {
    SETTINGS.lock().unwrap().cache = on;
}

pub fn set_dump(on: bool) {
    SETTINGS.lock().unwrap().dump = on;
}

pub fn set_cache_dir(dir: &std::path::Path) {
    SETTINGS.lock().unwrap().cache_dir = Some(dir.to_path_buf());
}

pub fn set_version_tag(tag: &str) {
    SETTINGS.lock().unwrap().version_tag = tag.to_string();
}

/// Every generator call that was run (not served from the cache) in this process, as
/// `generator(Type)`. Tests count their own generators in it.
pub fn launch_log() -> Vec<String> {
    LAUNCHES.lock().unwrap().clone()
}

pub(super) fn log_launch(entry: String) {
    LAUNCHES.lock().unwrap().push(entry);
}

thread_local! {
    static DRIVER: Cell<bool> = const { Cell::new(false) };
    static SOURCE_MAP: RefCell<Vec<GenUnit>> = const { RefCell::new(Vec::new()) };
}

/// True while the program that runs the generators is being compiled.
pub fn driver_mode() -> bool {
    DRIVER.with(|d| d.get())
}

pub(super) fn set_driver_mode(on: bool) -> bool {
    DRIVER.with(|d| d.replace(on))
}

pub(super) const GEN_BASE: u32 = 100_000_000;
const GEN_STRIDE: u32 = 100_000;

/// One piece of generated text and where it came from. Generated text keeps its own line
/// numbers, far above any real file, so an error can be mapped back.
#[derive(Clone, Debug)]
pub(super) struct GenUnit {
    pub base: u32,
    pub generator: String,
    pub ty: String,
    pub site_line: u32,
    pub site: String,
    pub module: String,
    pub lines: Vec<String>,
}

pub(super) fn clear_units() {
    SOURCE_MAP.with(|m| m.borrow_mut().clear());
}

/// Registers a unit and returns its line base: line `k` of the generated text is `base + k`.
pub(super) fn register_unit(mut unit: GenUnit) -> u32 {
    SOURCE_MAP.with(|m| {
        let mut m = m.borrow_mut();
        unit.base = GEN_BASE + m.len() as u32 * GEN_STRIDE;
        let base = unit.base;
        m.push(unit);
        base
    })
}

/// The line in the user's code a line stands for: itself, or the use site of the generated text
/// it belongs to.
pub fn user_line(line: u32) -> u32 {
    if line < GEN_BASE {
        return line;
    }
    SOURCE_MAP.with(|m| {
        let m = m.borrow();
        let idx = ((line - GEN_BASE) / GEN_STRIDE) as usize;
        m.get(idx).map_or(line, |u| u.site_line)
    })
}

/// Rewrites a compiler error whose line is inside generated text: it is reported at the use
/// site, names the generator and shows the generated line (spec `comptime-reflection`,
/// diagnostics). Other errors are returned unchanged.
pub fn map_error(e: String) -> String {
    const MARK: &str = ".zila:";
    let Some(p) = e.find(MARK) else { return e };
    let rest = &e[p + MARK.len()..];
    let digits: String = rest.chars().take_while(|c| c.is_ascii_digit()).collect();
    let Ok(line) = digits.parse::<u32>() else { return e };
    if line < GEN_BASE {
        return e;
    }
    let msg = rest[digits.len()..].trim_start_matches(':').trim_start().to_string();
    SOURCE_MAP.with(|m| {
        let m = m.borrow();
        let idx = ((line - GEN_BASE) / GEN_STRIDE) as usize;
        let Some(u) = m.get(idx) else { return e.clone() };
        let k = (line - u.base) as usize;
        let text = u.lines.get(k.wrapping_sub(1)).cloned().unwrap_or_default();
        format!(
            "{}.zila:{}: error in code generated by `{}` for `{}` ({}): {}\n  generated line {}: {}",
            u.module,
            u.site_line,
            u.generator,
            u.ty,
            u.site,
            msg,
            k,
            text.trim_end()
        )
    })
}
